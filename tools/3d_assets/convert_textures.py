"""Embed the ground textures: assets/3d/textures/<layer>.png -> src/video/ground3d_textures.h.

Standard library only. Layer order matches Ground3D::Layer (src/video/ground3d.h) and the TABLE
in ground_textures.py. Each texel is stored as 0x00RRGGBB, uploaded as GL_BGRA with
GL_UNSIGNED_INT_8_8_8_8_REV, so the table is independent of host byte order.
"""
import json
import struct
import sys
import zlib
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parents[1] / 'OpenTTD-15.3' / 'OpenTTD-15.3'
TEXTURES = ROOT / 'assets' / '3d' / 'textures'
OUTPUT = ROOT / 'src' / 'video' / 'ground3d_textures.h'
SIZE = 128
LAYERS = ([f'grass_{d}' for d in range(4)] + ['rough', 'rocks'] + [f'field_{k}' for k in range(9)]
	+ [f'snow_{d}' for d in range(4)] + [f'desert_{d}' for d in range(4)] + ['beach', 'water', 'concrete'])


def read_png(path):
	"""8-bit RGB/RGBA, non-interlaced PNG -> list of (r, g, b) rows."""
	data = path.read_bytes()
	if data[:8] != b'\x89PNG\r\n\x1a\n':
		sys.exit(f'{path}: not a PNG')
	pos, idat, header = 8, b'', None
	while pos < len(data):
		length, kind = struct.unpack('>I4s', data[pos:pos + 8])
		body = data[pos + 8:pos + 8 + length]
		if kind == b'IHDR':
			header = struct.unpack('>IIBBBBB', body)
		elif kind == b'IDAT':
			idat += body
		pos += 12 + length
	width, height, depth, colour, _, _, interlace = header
	if depth != 8 or colour not in (2, 6) or interlace:
		sys.exit(f'{path}: need 8-bit RGB or RGBA without interlacing')
	channels = 3 if colour == 2 else 4
	stride = width * channels
	raw = zlib.decompress(idat)
	rows, previous = [], bytearray(stride)
	for y in range(height):
		kind = raw[y * (stride + 1)]
		line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
		for i in range(stride):
			left = line[i - channels] if i >= channels else 0
			up = previous[i]
			corner = previous[i - channels] if i >= channels else 0
			if kind == 1:
				line[i] = (line[i] + left) & 255
			elif kind == 2:
				line[i] = (line[i] + up) & 255
			elif kind == 3:
				line[i] = (line[i] + (left + up) // 2) & 255
			elif kind == 4:
				p = left + up - corner
				pa, pb, pc = abs(p - left), abs(p - up), abs(p - corner)
				line[i] = (line[i] + (left if pa <= pb and pa <= pc else up if pb <= pc else corner)) & 255
		rows.append([tuple(line[x * channels:x * channels + 3]) for x in range(width)])
		previous = line
	return width, height, rows


def main():
	missing = [n for n in LAYERS if not (TEXTURES / f'{n}.png').exists()]
	if missing:
		sys.exit(f'missing textures: {", ".join(missing)}; run: art.py textures')
	out = [
		'/* This file is part of OpenTTD and is licensed under the GNU General Public License version 2. */',
		'/** @file ground3d_textures.h Generated by tools/3d_assets/convert_textures.py from assets/3d/textures; do not edit. */',
		'#ifndef VIDEO_GROUND3D_TEXTURES_H',
		'#define VIDEO_GROUND3D_TEXTURES_H',
		'',
		'#include <array>',
		'#include <cstdint>',
		'',
		'namespace Ground3D {',
		f'static constexpr int TEXTURE_SIZE = {SIZE}; ///< Texels per side; one repeat covers two tiles.',
		f'static constexpr int TEXTURE_LAYERS = {len(LAYERS)};',
		'static constexpr const char *layer_names[TEXTURE_LAYERS] = {' + ', '.join(f'"{n}"' for n in LAYERS) + '};',
	]
	averages, texels = [], []
	for name in LAYERS:
		width, height, rows = read_png(TEXTURES / f'{name}.png')
		if (width, height) != (SIZE, SIZE):
			sys.exit(f'{name}.png is {width}x{height}; expected {SIZE}x{SIZE}')
		# GL row 0 is the bottom; texture coordinates follow world X/Y, so store the image top row last.
		layer = [p for row in reversed(rows) for p in row]
		averages.append([sum(p[i] for p in layer) / len(layer) / 255 for i in range(3)])
		texels.append(layer)
	out.append('/** Mean sRGB colour per layer: the flat colour when textures are unavailable. */')
	out.append('static constexpr std::array<std::array<float, 3>, TEXTURE_LAYERS> average = {{')
	for name, a in zip(LAYERS, averages):
		out.append(f'\t{{{a[0]:.4f}f, {a[1]:.4f}f, {a[2]:.4f}f}}, // {name}')
	out.append('}};')
	out.append('/** 0x00RRGGBB texels, layer by layer, bottom row first. */')
	out.append('static constexpr uint32_t texels[TEXTURE_LAYERS * TEXTURE_SIZE * TEXTURE_SIZE] = {')
	for name, layer in zip(LAYERS, texels):
		out.append(f'\t/* {name} */')
		for i in range(0, len(layer), 16):
			out.append('\t' + ','.join(f'0x{r:02x}{g:02x}{b:02x}' for r, g, b in layer[i:i + 16]) + ',')
	out += ['};', '}', '', '#endif', '']
	with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as f:
		f.write('\n'.join(out))
	print(f'wrote {OUTPUT.relative_to(ROOT)}: {len(LAYERS)} layers of {SIZE}x{SIZE}')
	advance_inventory()


# Inventory texture identity -> the layers that replace its classic sprites.
IDENTITIES = {
	'texture_bare': ['grass_0'],
	'texture_grass': ['grass_1', 'grass_2', 'grass_3'],
	'texture_rough': ['rough'],
	'texture_rocks': ['rocks'],
	'texture_fields': [f'field_{k}' for k in range(9)],
	'texture_snow_desert': [f'snow_{d}' for d in range(4)] + [f'desert_{d}' for d in range(4)],
	'texture_water': ['water', 'beach'],
	'texture_concrete': ['concrete'],
}


def advance_inventory():
	"""Embedded textures move not_started -> modelled and approved -> in_game, like convert_gltf.py."""
	path = ROOT / 'assets' / '3d' / 'inventory.json'
	inventory = json.loads(path.read_text(encoding='utf-8'))
	changed = 0
	for entry in inventory['entries']:
		layers = IDENTITIES.get(entry['key'])
		if layers is None:
			continue
		entry['textures'] = layers
		status = {'not_started': 'modelled', 'approved': 'in_game'}.get(entry['status'], entry['status'])
		changed += status != entry['status']
		entry['status'] = status
	path.write_text(json.dumps(inventory, indent='\t') + '\n', encoding='utf-8')
	print(f'inventory: {changed} texture identities advanced')


if __name__ == '__main__':
	main()
